const assert = require('node:assert/strict');
const { create } = require('../static/data-runtime.js');
const memory = new Map([['sistema_pending_sync','legacy-pending'],['sistema_gestao_state_v1','legacy-state'],['sistema_perfil_pdi_v1_a','owned-pdi']]);
const storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const events=[];const a=create({storage,notify:e=>events.push(e)});
assert.equal(a.cache.getItem('sistema_pending_sync'),null);
assert.throws(()=>a.cache.setItem('private','no-session'));
a.cache.setItem('theme','dark');assert.equal(memory.get('theme'),'dark');
const token=a.bind({id:'a'});a.cache.setItem('sistema_pending_sync','owned-a');
assert.equal(a.cache.getItem('sistema_pending_sync'),'owned-a');assert.equal(memory.get('sistema_pending_sync'),'legacy-pending');
assert.equal(a.cache.getItem('sistema_perfil_pdi_v1_a'),'owned-pdi');assert.equal(a.cache.getItem('sistema_perfil_pdi_v1_b'),null);
a.state.publish('records',{view:[{Atendente:'Pessoa'}]},token);
const snapshot=a.state.get('records');snapshot.view[0].Atendente='alterado';assert.equal(a.state.get('records').view[0].Atendente,'Pessoa');
const b=create({storage});b.bind({id:'b'});assert.equal(b.cache.getItem('sistema_pending_sync'),null);
b.cache.setItem('sistema_pending_sync','owned-b');assert.equal(a.cache.getItem('sistema_pending_sync'),'owned-a');
a.invalidate();assert.equal(a.state.get('records'),null);assert.equal(a.current(token),false);assert.equal(a.cache.getItem('sistema_pending_sync'),null);
assert.throws(()=>a.cache.setItem('sistema_pending_sync','late'));assert.throws(()=>a.bind({id:'b'}));
assert.equal(a.state.publish('records',{view:['late']},token),false);assert.equal(memory.get('sistema_gestao_state_v1'),'legacy-state');
assert.ok(events.every(e=>!('view'in e)));assert.ok(events.some(e=>e.reason==='invalidated'));
console.log('Runtime: cache isolado, legado preservado, PDI compatível, snapshots sem mutação externa, eventos e invalidação de sessão verificados.');
